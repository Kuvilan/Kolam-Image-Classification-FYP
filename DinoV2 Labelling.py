import os
import shutil
import torch
from torchvision import transforms
from PIL import Image
import numpy as np
from tqdm import tqdm

# ==========================================
# 1. SETUP GOOGLE DRIVE PATHS
# ==========================================
# This points directly to the folder you created in your Google Drive
BASE_DIR = "/content/drive/MyDrive/Kolam_Project"

LABELED_CATEGORIES = [
    "Artifical Kolam", "Digital Art Kolam", "Mandala Kolam",
    "Peakcock Kolam", "Pushpa Kolam (Pookalam)", "Rangoli Kolam",
    "Sikku & Pulli Kolam (Geometric Patterns)",
    "Traditional Kolam (Colourful)", "Traditional Kolam (Dominant White Colour)"
]

UNKNOWN_DIR = os.path.join(BASE_DIR, "Unknown")
OUTPUT_DIR = os.path.join(BASE_DIR, "Sorted_Output")

# Verify GPU is active
device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
print(f"Using device: {device} (If this says 'cpu', check your Runtime settings!)")

# ==========================================
# 2. LOAD DINOv2 MODEL
# ==========================================
print("Loading DINOv2 model...")
dinov2 = torch.hub.load('facebookresearch/dinov2', 'dinov2_vits14').to(device)
dinov2.eval()

transform = transforms.Compose([
    transforms.Resize((224, 224)),
    transforms.ToTensor(),
    transforms.Normalize(mean=[0.485, 0.456, 0.406], std=[0.229, 0.224, 0.225]),
])

def get_embedding(image_path):
    try:
        img = Image.open(image_path).convert('RGB')
        tensor = transform(img).unsqueeze(0).to(device)
        with torch.no_grad():
            emb = dinov2(tensor)
            emb = torch.nn.functional.normalize(emb, dim=1)
        return emb.cpu().numpy().flatten()
    except Exception as e:
        return None

# ==========================================
# 3. BUILD PROFILES FOR THE 9 LABELS
# ==========================================
print("\n--- Phase 1: Generating style vectors ---")
category_centroids = {}
valid_exts = ('.png', '.jpg', '.jpeg', '.webp', '.bmp')

for category in LABELED_CATEGORIES:
    category_path = os.path.join(BASE_DIR, category)
    if not os.path.exists(category_path):
        print(f"Warning: Folder '{category}' not found at {category_path}. Skipping.")
        continue

    embeddings = []
    print(f"Processing reference images in '{category}'...")
    for img_name in os.listdir(category_path):
        if img_name.lower().endswith(valid_exts):
            emb = get_embedding(os.path.join(category_path, img_name))
            if emb is not None:
                embeddings.append(emb)

    if embeddings:
        category_centroids[category] = np.mean(embeddings, axis=0)

# ==========================================
# 4. SORT THE 1,500 UNKNOWN IMAGES
# ==========================================
print("\n--- Phase 2: Sorting unknown kolams ---")
if not os.path.exists(UNKNOWN_DIR):
    raise FileNotFoundError(f"Could not find the 'Unknown' folder at {UNKNOWN_DIR}")

unknown_files = [f for f in os.listdir(UNKNOWN_DIR) if f.lower().endswith(valid_exts)]
print(f"Found {len(unknown_files)} images to sort.")

for img_name in tqdm(unknown_files, desc="Sorting Progress"):
    unknown_path = os.path.join(UNKNOWN_DIR, img_name)
    unknown_emb = get_embedding(unknown_path)

    if unknown_emb is not None:
        best_match = None
        min_distance = float('inf')

        for category, centroid in category_centroids.items():
            distance = np.linalg.norm(unknown_emb - centroid)
            if distance < min_distance:
                min_distance = distance
                best_match = category

        if best_match is not None:
            target_folder = os.path.join(OUTPUT_DIR, best_match)
            os.makedirs(target_folder, exist_ok=True)
            shutil.copy(unknown_path, os.path.join(target_folder, img_name))

print(f"\nSuccess! Check your Google Drive. Your sorted images are in: {OUTPUT_DIR}")

